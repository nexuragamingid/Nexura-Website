// Runs before every `wrangler dev` and `wrangler deploy` (see [build] in wrangler.toml).
//   1. copies the public pages into ./site (scripts/build-site.mjs)
//   2. writes ./site/_headers: security headers for every page
//   3. writes src/generated.js: the schema and catalogue seed the Worker applies to its own
//      database when they change, so a deploy needs no separate database step
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import './build-site.mjs';
import { seedStatements } from './seed.mjs';

const here = (p) => new URL(p, import.meta.url);
const production = process.env.NEXURA_ENV === 'production';

writeFileSync(here('../site/_headers'), `/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(self), microphone=(), geolocation=(), payment=()
${production ? '' : '  X-Robots-Tag: noindex, nofollow\n'}
/admin/*
  X-Robots-Tag: noindex, nofollow
  Cache-Control: no-store
`);

const schema = readFileSync(here('../schema.sql'), 'utf8')
  .split('\n').map((line) => line.replace(/--.*$/, '')).join('\n')
  .split(';').map((q) => q.replace(/\s+/g, ' ').trim())
  .filter((q) => q && !/^PRAGMA/i.test(q));
const version = createHash('sha256').update(JSON.stringify([schema, seedStatements])).digest('hex').slice(0, 16);
const generated = `// Generated by scripts/build.mjs from schema.sql and assets/js/data.js. Do not edit.
export const VERSION = ${JSON.stringify(version)};
export const SCHEMA = ${JSON.stringify(schema, null, 2)};
export const SEED = ${JSON.stringify(seedStatements, null, 2)};
`;
// Only written when it changed, so the dev server's file watcher is not set off in a loop.
const target = here('../src/generated.js');
if (!existsSync(target) || readFileSync(target, 'utf8') !== generated) writeFileSync(target, generated);
console.log(`build: ${schema.length} schema statements, ${seedStatements.length} seed statements, version ${version}`);
